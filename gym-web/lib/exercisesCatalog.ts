/** Ejercicios que entrenan el músculo. El calentamiento no entra en esta lista. */
export function exercisesForMuscle(id: MuscleId | null) {
  if (!id || id === "full-body") return EXERCISES;
  return EXERCISES
    .filter((exercise) => exercise.primary === id || exercise.secondary.includes(id))
    .slice()
    .sort((a, b) => Number(b.primary === id) - Number(a.primary === id));
}

/** Ejercicios que solo mencionan el músculo en la preparación. */
export function exercisesForWarmupMuscle(id: MuscleId) {
  return EXERCISES.filter((exercise) => exercise.warmup.includes(id));
}
